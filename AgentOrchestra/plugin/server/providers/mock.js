import { clamp, nowIso, sleepSync } from "../util.js";

function simulatedNotice() {
  return "> SIMULATED OUTPUT — generated by AgentOrchestra's mock provider. Not engineering evidence, not a CAD model, and not a test result.";
}

function padTo(text, minChars) {
  let output = text;
  let index = 0;
  const sentence = "\n\nScope note: this is a deterministic structural fixture used only to test orchestration, routing, locking and review behavior.";
  while (output.length < minChars && index < 80) {
    output += sentence;
    index += 1;
  }
  return output;
}

function artifactContent(task, artifactPath, quality, attempt) {
  const terms = task.acceptance?.mustContain ?? [];
  const lower = artifactPath.toLowerCase();
  const base = {
    taskId: task.id,
    title: task.title,
    simulated: true,
    attempt,
    quality: Math.round(quality * 10) / 10,
    generatedAt: nowIso(),
    note: "Mock fixture. No real execution or engineering verification occurred."
  };
  if (lower.endsWith(".json")) {
    if (task.kind === "review" || task.acceptance?.requireJsonVerdict) {
      const passed = quality >= 55;
      return JSON.stringify({
        ...base,
        score: Math.round(clamp(quality, 0, 100)),
        pass: passed,
        issues: passed ? [] : ["Simulated reviewer found the fitted quality below the review bar."],
        residual_risks: [
          "All findings are simulated; a human must review real artifacts.",
          "No live model, CAD kernel, or test runner was invoked."
        ]
      }, null, 2);
    }
    const object = { ...base, status: "simulated-ok" };
    for (const key of task.acceptance?.jsonKeys ?? []) {
      if (!(key in object)) object[key] = key === "score" ? Math.round(quality) : key === "pass" ? true : [`simulated:${key}`];
    }
    return JSON.stringify(object, null, 2);
  }
  if (lower.endsWith(".js") || lower.endsWith(".mjs")) {
    return [
      "// SIMULATED OUTPUT — mock provider fixture, not production code.",
      `// Task: ${task.id}`,
      ...terms.map((term) => `// Requirement marker: ${term}`),
      "export function run(input) {",
      "  return { ok: true, simulated: true, input };",
      "}",
      "",
      "export const meta = { simulated: true, taskId: " + JSON.stringify(task.id) + " };"
    ].join("\n");
  }
  if (lower.endsWith(".py")) {
    return [
      "# SIMULATED OUTPUT — mock provider fixture, not production code.",
      `# Task: ${task.id}`,
      ...terms.map((term) => `# Requirement marker: ${term}`),
      "def run(payload):",
      "    return {\"ok\": True, \"simulated\": True, \"payload\": payload}"
    ].join("\n");
  }
  if (lower.endsWith(".scad")) {
    return [
      "// SIMULATED OUTPUT — no CAD kernel was invoked.",
      `// Task: ${task.id}`,
      "module simulated_part() {",
      "  // dimensions intentionally omitted",
      "  cube([1, 1, 1]);",
      "}",
      "simulated_part();"
    ].join("\n");
  }
  if (lower.endsWith(".csv")) {
    return ["key,value", "simulated,true", `task,${task.id}`, `quality,${Math.round(quality)}`].join("\n");
  }
  const termList = terms.length ? terms.map((term) => `- ${term}`).join("\n") : "- No explicit keyword requirement.";
  return [
    `# ${task.title}`,
    "",
    simulatedNotice(),
    "",
    "## Summary",
    task.brief || "No brief supplied.",
    "",
    "## Deliverable",
    `A structural fixture for task \`${task.id}\` was produced by a model with fitted quality ${Math.round(quality)}.`,
    "It exists to exercise routing, dependency ordering, review gates, and artifact versioning.",
    "",
    "## Requirement markers",
    termList,
    "",
    "## Evidence",
    "- Evidence class: simulated",
    "- Command: none (simulation)",
    "- Output: structural fixture only; no command was executed",
    "",
    "## Risks and unknowns",
    "- This is not a real engineering result.",
    "- No live test, CAD operation, or external verification occurred.",
    "- Acceptance still requires a real provider and human review.",
    "",
    "## Next actions",
    "- Replace mock models with verified providers.",
    "- Re-run with real evidence before any engineering decision.",
    "",
    `Artifact: \`${artifactPath}\``
  ].join("\n");
}

export class MockProvider {
  constructor({ name = "mock" } = {}) {
    this.name = name;
    this.simulated = true;
  }

  async probe() {
    return { available: true, detail: "offline deterministic mock provider" };
  }

  async run({ task, model, prompt = "", role = "execute", attempt = 1, context = {} }) {
    const latency = Math.min(80, Math.max(5, Number(model.latencyMs ?? 30) / 8));
    sleepSync(Math.round(latency));

    if (role === "reviewer") {
      const targetScore = Number(context.reviewTargetScore ?? 60);
      const issues = context.deterministicIssues ?? [];
      const deterministicPass = context.deterministicPass !== false;
      const qualityShift = (Number(context.quality ?? 70) - 70) * 0.25;
      const score = Math.round(clamp(targetScore + qualityShift, 0, 100));
      const pass = deterministicPass && score >= Number(context.minReviewScore ?? 70);
      const output = JSON.stringify({
        score,
        pass,
        issues: pass ? issues : [...issues, "Simulated reviewer: quality is below the configured review bar."],
        residual_risks: [
          "Review is simulated; it is not an independent real-world audit.",
          "A human must inspect the underlying artifacts before acceptance."
        ],
        simulated: true
      }, null, 2);
      return {
        output,
        artifacts: [],
        tokensIn: Math.ceil(prompt.length / 3),
        tokensOut: Math.ceil(output.length / 3),
        costCny: 0,
        latencyMs: latency,
        meta: { provider: this.name, modelId: model.id, simulated: true, role, attempt, evidenceClass: "simulated" }
      };
    }

    const quality = Number(context.quality ?? context.routeQuality ?? 60);
    const refusal = quality < Number(context.minQuality ?? 0) + 1 ||
      (task.failFirstAttempt && attempt === 1 && quality < 90);
    if (refusal) {
      const output = [
        "INSUFFICIENT_CAPABILITY — simulated failure",
        `The fitted quality for ${model.id} is ${quality.toFixed(1)}, below the required bar of ${context.minQuality ?? "unknown"}.`,
        "No artifact was produced. The orchestrator should escalate the model or stop for human review."
      ].join("\n");
      return {
        output,
        artifacts: [],
        tokensIn: Math.ceil(prompt.length / 3),
        tokensOut: Math.ceil(output.length / 3),
        costCny: 0,
        latencyMs: latency,
        meta: { provider: this.name, modelId: model.id, simulated: true, role, attempt, refusal: true, evidenceClass: "simulated" }
      };
    }

    if (task.kind === "review" || task.acceptance?.requireJsonVerdict) {
      const passed = quality >= 55;
      const verdict = {
        score: Math.round(quality),
        pass: passed,
        issues: passed ? [] : ["Simulated review: fitted quality below bar."],
        residual_risks: ["Simulated verdict; no real artifact inspection."],
        simulated: true,
        taskId: task.id
      };
      const artifacts = (task.acceptance?.artifacts ?? []).map((artifactPath) => ({
        path: artifactPath,
        content: artifactContent(task, artifactPath, quality, attempt)
      }));
      const output = `${JSON.stringify(verdict, null, 2)}\n\n${simulatedNotice()}`;
      return {
        output,
        artifacts,
        tokensIn: Math.ceil(prompt.length / 3),
        tokensOut: Math.ceil(output.length / 3),
        costCny: 0,
        latencyMs: latency,
        meta: { provider: this.name, modelId: model.id, simulated: true, role, attempt, evidenceClass: "simulated" }
      };
    }

    const artifacts = (task.acceptance?.artifacts ?? []).map((artifactPath) => ({
      path: artifactPath,
      content: padTo(artifactContent(task, artifactPath, quality, attempt), Math.max(0, Number(task.acceptance?.minChars ?? 0) / Math.max(1, task.acceptance?.artifacts?.length ?? 1)))
    }));

    const termList = (task.acceptance?.mustContain ?? []).map((term) => `- ${term}`).join("\n") || "- None";
    const codeArtifact = artifacts.find((artifact) => /\.(js|mjs|py|ts|scad)$/i.test(artifact.path));
    const codeBlock = task.acceptance?.requireCodeBlock
      ? [
          "## Code excerpt",
          "```" + (/\.py$/i.test(codeArtifact?.path ?? "") ? "python" : "js"),
          codeArtifact?.content ?? "// simulated code fixture\nexport function simulated() { return true; }",
          "```",
          ""
        ].join("\n")
      : "";
    const output = padTo([
      `# ${task.title}`,
      "",
      simulatedNotice(),
      "",
      "## Summary",
      task.brief || "No brief supplied.",
      "",
      "## Requirements covered",
      termList,
      "",
      "## Deliverable",
      artifacts.length
        ? `Produced ${artifacts.length} simulated artifact(s): ${artifacts.map((item) => `\`${item.path}\``).join(", ")}.`
        : "No file artifact was requested; this is the complete simulated response.",
      "",
      codeBlock,
      "## Evidence",
      "- Evidence class: simulated",
      "- Command: none (simulation)",
      "- Output: structural generation only",
      "",
      "## Risks and unknowns",
      "- This result is not real engineering evidence.",
      "- Replace the mock provider before making any decision.",
      "",
      "## Next actions",
      "- Verify with a real provider.",
      "- Keep the human acceptance gate closed until evidence exists."
    ].join("\n"), Number(task.acceptance?.minChars ?? 0));

    return {
      output,
      artifacts,
      tokensIn: Math.ceil(prompt.length / 3),
      tokensOut: Math.ceil(output.length / 3),
      costCny: 0,
      latencyMs: latency,
      meta: {
        provider: this.name,
        modelId: model.id,
        simulated: true,
        role,
        attempt,
        evidenceClass: "simulated"
      }
    };
  }
}
